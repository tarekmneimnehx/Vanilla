type Leaves<T> = T extends string
  ? never
  : T extends readonly string[]
    ? never
    : T extends { one: string; other: string }
      ? never
      : { [K in keyof T & string]: T[K] extends string | readonly string[] | { one: string; other: string } ? K : `${K}.${Leaves<T[K]>}` }[keyof T & string];

export type TranslationKey = Leaves<typeof en>;

type DeepReplace<T> = T extends string
  ? string
  : T extends readonly string[]
    ? readonly string[]
    : T extends { one: string; other: string }
      ? { zero?: string; one: string; two?: string; few?: string; many?: string; other: string }
      : { [K in keyof T]: DeepReplace<T[K]> };

export type Translation = DeepReplace<typeof en>;
